export function getIntegrationCopyLabel(snippet: IntegrationSnippet): string {
  return (snippet.kind === 'steps' && snippet.copyLabel) || INTEGRATION_COPY_LABELS[snippet.kind];
}

/** Plain text for the clipboard: no `$` prompts, notes or file label. */
export function getIntegrationCopyText(snippet: IntegrationSnippet): string {
  switch (snippet.kind) {
    case 'commands':
      return snippet.lines.join('\n');
    case 'config':
      return snippet.code;
    case 'steps':
      return snippet.copy;
  }
}
