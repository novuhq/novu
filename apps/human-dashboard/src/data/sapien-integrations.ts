/** Notes around a snippet, in muted text that wraps: what to do first, and what follows. Never copied. */
export type SnippetNotes = { before?: string; after?: string };

export type IntegrationSnippet = SnippetNotes &
  (
    | /**
     * Shell commands, rendered with a decorative `$` prompt. A line that ends in `\` goes on in the next,
     * indented one, which has no prompt. Empty strings are blank lines.
     */
    { kind: 'commands'; lines: readonly string[] }
    /** A config file: `file` is shown above the code but is never copied. */
    | { kind: 'config'; file: string; code: string }
    /** Lines typed into an app, without prompts; only `copy` goes to the clipboard, under `copyLabel` if set. */
    | { kind: 'steps'; lines: readonly string[]; copy: string; copyLabel?: string }
  );

export type Integration = {
  id: string;
  label: string;
  snippet: IntegrationSnippet;
};

